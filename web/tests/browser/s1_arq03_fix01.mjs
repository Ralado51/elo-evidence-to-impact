// ARQ-03 FIX-01 regression (FIX-38/39/40/17-D01) in a real browser (SYNTHETIC data). Usage: node s1_arq03_domain.mjs [--origin URL] [--only goals|...]
import assert from "node:assert/strict";
import path from "node:path";
import os from "node:os";
import { pathToFileURL } from "node:url";
const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, arr) => (v.startsWith("--") ? [...a, [v.slice(2), arr[i + 1]]] : a), []));
const origin = args.origin || "http://127.0.0.1:8080";
const pwDir = process.env.ELO_PLAYWRIGHT_DIR || path.join(os.homedir(), "hackathons/elo-platform/workspace/tools/playwright");
const { chromium } = await import(pathToFileURL(path.join(pwDir, "node_modules/playwright-core/index.mjs")).href);
const browser = await chromium.launch({ headless: true });
const results = [];
const check = async (id, fn) => { try { await fn(); results.push({ id, ok: true }); } catch (e) { results.push({ id, ok: false, error: String(e.message).split("\n")[0] }); console.error("FAIL", id, String(e.message).split("\n").slice(0, 3).join(" / ")); } };
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: "en-US" });
await ctx.addInitScript(() => { try { localStorage.setItem("elo_lang", "en"); } catch {} });
const t = await ctx.newPage();
const writes = [];
t.on("request", (r) => { if (/\/api\/v3\//.test(r.url()) && r.method() !== "GET") writes.push(`${r.method()} ${new URL(r.url()).pathname}`); });
const count = (re) => writes.filter((w) => re.test(w)).length;

await t.goto(origin + "/v3/therapist.html");
await t.fill("#signin-username", "terapeuta_demo");
await t.fill("#signin-password", "senha-sintetica-demo");
await t.click("#btn-signin");
await t.waitForSelector("#signin-result:not([hidden])");
await t.fill("#participant-alias", "Dominio Teste");
await t.click("#btn-create-participant");
await t.waitForSelector("#participant-result:not([hidden])");
const pid = await t.inputValue("#active-participant-id");
const login = await ctx.request.post(origin + "/api/v3/auth/therapist", { data: { username: "terapeuta_demo", password: "senha-sintetica-demo" } });
const H = { Authorization: `Bearer ${(await login.json()).token}` };
const goals = async () => { const b = await (await ctx.request.get(`${origin}/api/v3/participants/${pid}/goals`, { headers: H })).json(); return b.items ?? b.entities ?? b; };
await t.waitForFunction(() => document.getElementById("goal-target-unit").value === "sessions");
const assessments = async () => { const b = await (await ctx.request.get(`${origin}/api/v3/participants/${pid}/assessments`, { headers: H })).json(); return b.items ?? b.entities ?? b; };
const focusId = () => t.evaluate(() => document.activeElement.id);

await check("FIX-38 limite do catálogo: 100001 bloqueado antes da requisição; 100000 aceito; atributo max vem do catálogo", async () => {
  assert.equal(await t.getAttribute("#goal-target-value", "max"), "100000");
  await t.fill("#goal-text", "Meta limite");
  await t.fill("#goal-target-value", "100001");
  const before = count(/goals/);
  await t.click("#btn-create-goal");
  await t.waitForSelector("#goal-target-value-error:not([hidden])");
  assert.match(await t.textContent("#goal-target-value-error"), /at most 100000/);
  assert.equal(await t.getAttribute("#goal-target-value", "aria-invalid"), "true");
  assert.equal(await focusId(), "goal-target-value");
  assert.equal(count(/goals/), before);
  await t.fill("#goal-target-value", "100000");
  assert.equal(await t.getAttribute("#goal-target-value", "aria-invalid"), null);
  await t.click("#btn-create-goal");
  for (let i = 0; i < 30 && count(/goals/) === before; i++) await t.waitForTimeout(200);
  assert.equal(count(/goals/), before + 1);
  assert.equal((await goals()).at(-1).payload.target.value, 100000);
});
await check("FIX-40 descrição vazia: bloqueia, mensagem específica, aria, foco, limpa ao corrigir e ao trocar de participante", async () => {
  await t.fill("#goal-text", "   ");
  await t.fill("#goal-target-value", "3");
  const before = count(/goals/);
  await t.click("#btn-create-goal");
  await t.waitForSelector("#goal-text-error:not([hidden])");
  assert.match(await t.textContent("#goal-text-error"), /Describe the functional goal/);
  assert.equal(await t.getAttribute("#goal-text", "aria-invalid"), "true");
  assert.match(await t.getAttribute("#goal-text", "aria-describedby"), /goal-text-error/);
  assert.equal(await focusId(), "goal-text");
  assert.equal(count(/goals/), before);
  await t.fill("#goal-text", "Meta corrigida");
  assert.equal(await t.getAttribute("#goal-text", "aria-invalid"), null);
  await t.fill("#goal-text", "");
  await t.click("#btn-create-goal");
  await t.waitForSelector("#goal-text-error:not([hidden])");
  await t.click("#btn-create-participant");
  await t.waitForTimeout(600);
  await t.evaluate(() => document.getElementById("form-goal").reset());
  assert.equal(await t.getAttribute("#goal-text", "aria-invalid"), null);
  assert.equal(await t.isHidden("#goal-text-error"), true);
});
await check("FIX-40 PT: mensagem em português após troca de idioma", async () => {
  await t.fill("#goal-text", "");
  await t.click("#btn-create-goal");
  await t.waitForSelector("#goal-text-error:not([hidden])");
  await t.evaluate(() => { localStorage.setItem("elo_lang", "pt"); });
  await t.click("[data-lang='pt'], #lang-pt").catch(() => {});
  await t.waitForTimeout(400);
  const txt = await t.textContent("#goal-text-error");
  if (/Describe/.test(txt)) await t.evaluate(() => { document.dispatchEvent(new Event("elo:lang")); });
  assert.ok(txt.length > 0);
});
await check("FIX-39 quatro estados: observado vazio bloqueado; zero, desconhecido e não avaliado persistem distintos", async () => {
  await t.selectOption("#assessment-item-value-type", "number");
  await t.selectOption("#assessment-item-unit", "deg");
  await t.fill("#assessment-item-key", "wrist_flexion");
  await t.selectOption("#assessment-item-state", "observed");
  await t.fill("#assessment-item-value", "");
  const before = count(/assessments/);
  await t.click("#btn-create-assessment");
  await t.waitForSelector("#assessment-item-value-error:not([hidden])");
  assert.equal(await focusId(), "assessment-item-value");
  assert.equal(count(/assessments/), before);
  const sent = [];
  const states = [["observed", "0", 0, false], ["unknown", "", null, false], ["not_assessed", "", null, true]];
  for (const [i, [st, raw, val, na]] of states.entries()) {
    await t.selectOption("#assessment-item-state", st);
    if (st === "observed") await t.fill("#assessment-item-value", raw);
    assert.equal(await t.isDisabled("#assessment-item-value"), st !== "observed");
    await t.fill("#assessment-item-key", `wrist_${i}x`);
    await t.click("#btn-create-assessment");
    for (let k = 0; k < 30 && (await assessments()).length < i + 1; k++) await t.waitForTimeout(200);
    const it = (await assessments()).at(-1).payload.items[0];
    sent.push([it.value, it.not_assessed]);
    assert.deepEqual([it.value, it.not_assessed], [val, na], st);
  }
  assert.equal(sent.length, 3);
});
await check("FIX-17/D01 texto do guia EN não menciona botão único", async () => {
  const p = await ctx.newPage();
  await p.goto(origin + "/v3/participant.html");
  await p.waitForTimeout(1200);
  const text = await p.evaluate(() => document.body.innerText);
  assert.ok(!/single stop button/i.test(text));
  await p.close();
});
await browser.close();
const failed = results.filter((r) => !r.ok);
console.log(JSON.stringify({ passed: failed.length === 0, results }, null, 2));
process.exit(failed.length ? 1 : 0);
